import test from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { randomUUID } from 'node:crypto';
import pg from 'pg';
import { getPool, transaction } from '../src/server/db.mjs';
import { seedFixtures } from '../src/server/fixtures.mjs';
import { getPortalData, handleAction, handleSync } from '../src/server/service.mjs';
import { signSyncToken } from '../src/server/auth.mjs';
import { beginBattleNet, finishBattleNet } from '../src/server/battlenet.mjs';
const enabled = process.env.RUN_DB_TESTS === '1' && Boolean(process.env.DATABASE_URL);
test('PostgreSQL sessions, permissions, tokens, imports, requests, titles and offers', {skip:!enabled}, async()=>{
  const admin = new pg.Pool({connectionString:process.env.DATABASE_URL});
  const schema = `test_${randomUUID().replaceAll('-','')}`;
  await admin.query(`CREATE SCHEMA ${schema}`);
  const oldUrl = process.env.DATABASE_URL;
  const dbUrl = new URL(oldUrl); dbUrl.searchParams.set('options',`-csearch_path=${schema}`); process.env.DATABASE_URL = dbUrl.href;
  process.env.ENABLE_LOCAL_TEST_LOGIN = 'true'; process.env.NODE_ENV = 'development'; process.env.APP_ORIGIN = 'http://localhost:4321';
  process.env.SYNC_JWT_SECRET = 'integration-test-only-signing-key-over-thirty-two-bytes';
  const req = (path,body,cookie) => new Request(`http://localhost:4321${path}`,{method:body?'POST':'GET',headers:{origin:'http://localhost:4321',...(cookie?{cookie}:{})},...(body?{body:JSON.stringify(body)}:{})});
  const act = (body,cookie) => handleAction(req('/api/actions',body,cookie),'127.0.0.1');
  const upload = (body,token) => handleSync(new Request('http://localhost:4321/api/sync',{method:'POST',headers:{authorization:`Bearer ${token}`},body:JSON.stringify(body)}),'127.0.0.1');
  try {
    await getPool().query(await readFile(new URL('../migrations/001_portal.sql',import.meta.url),'utf8'));
    await transaction(db=>seedFixtures(db));
    assert.equal((await getPortalData(req('/account'))).account,null);
    await assert.rejects(()=>handleAction(req('/api/actions',{action:'local-login',persona:'owner'}),'192.0.2.1'));
    const owner = (await act({action:'local-login',persona:'owner'})).cookie.split(';')[0];
    const member = (await act({action:'local-login',persona:'member'})).cookie.split(';')[0];
    const memberData = await getPortalData(req('/account',null,member));
    assert.equal(memberData.account.role,'member'); assert.equal(memberData.characters.length,1);
    await assert.rejects(()=>act({action:'issue-token',scope:'guild'},member));
    await assert.rejects(()=>act({action:'set-title',characterId:'fixture-owner-character',title:'Guild Alchemist',assigned:true},member));
    const ownerToken = (await act({action:'issue-token',scope:'guild'},owner)).token;
    const memberToken = (await act({action:'issue-token',scope:'member'},member)).token;
    const body = {schemaVersion:1,snapshotId:'integration-capture',capturedAt:Math.floor(Date.now()/1000),source:{addonVersion:'0.1.0',character:{name:'Test Owner',realm:'Test Realm'},guild:{name:'Band of the Helping Hand',realm:'Test Realm',region:'us'}},characters:[{name:'Test Owner',realm:'Test Realm'}],banks:[{name:'Test Bank',realm:'Test Realm',guildName:'Band of the Helping Hand',viewOnly:false,complete:false,observedAt:null,items:[{itemId:118,count:25,name:'Minor Healing Potion'}]}]};
    await assert.rejects(()=>upload(body,memberToken));
    assert.equal((await upload(body,ownerToken)).ok,true);
    assert.equal((await upload(body,ownerToken)).duplicate,true);
    await assert.rejects(()=>upload({...body,characters:[]},ownerToken));
    assert.equal((await getPortalData(req('/bank',null,member))).bank[0].count,25);
    await act({action:'favorite',itemKey:'118:0:0'},member);
    await act({action:'request-item',itemKey:'118:0:0',quantity:3,characterId:'fixture-member-character'},member);
    await assert.rejects(()=>act({action:'request-item',itemKey:'118:0:0',quantity:1,characterId:'fixture-owner-character'},member));
    const request = (await getPortalData(req('/bank',null,member))).requests[0];
    await assert.rejects(()=>act({action:'update-request',id:request.id,status:'approved'},member));
    await act({action:'update-request',id:request.id,status:'approved'},owner);
    await act({action:'update-request',id:request.id,status:'fulfilled'},owner);
    const after = await getPortalData(req('/bank',null,member));
    assert.equal(after.bank[0].count,25); assert.equal(after.bank[0].favorite,true); assert.equal(after.requests[0].status,'fulfilled');
    await act({action:'set-title',characterId:'fixture-member-character',title:'Guild Alchemist',assigned:true},owner);
    await act({action:'set-title',characterId:'fixture-member-character',title:'Guild Enchanter',assigned:true},owner);
    await act({action:'set-title',characterId:'fixture-owner-character',title:'Guild Alchemist',assigned:true},owner);
    assert.equal((await getPortalData(req('/account',null,member))).characters[0].titles.length,2);
    await act({action:'set-offer',recipeKey:'fixture-member-character:171:2330',offered:true},member);
    assert.equal((await getPortalData(req('/professions',null,owner))).professions.find(p=>p.characterId === 'fixture-member-character').recipes[0].offered,true);
    const tokens = (await getPortalData(req('/account',null,owner))).tokens;
    assert.equal(JSON.stringify(tokens).includes(ownerToken),false);
    await act({action:'revoke-token',id:tokens[0].id},owner);
    await assert.rejects(()=>upload({...body,snapshotId:'revoked-capture'},ownerToken));
    const nextToken = (await act({action:'issue-token',scope:'guild'},owner)).token;
    await getPool().query("UPDATE memberships SET role='member' WHERE account_id='fixture-owner'");
    await assert.rejects(()=>upload({...body,snapshotId:'demoted-capture'},nextToken));
    await getPool().query("UPDATE memberships SET active=false WHERE account_id='fixture-member'");
    const removed = await getPortalData(req('/bank',null,member));
    assert.equal(removed.guild,null); assert.deepEqual(removed.bank,[]);
    const expired = signSyncToken({iss:'helping-hand',aud:'helping-hand-sync',sub:'fixture-member',guild:'fixture-guild',jti:'x',scope:'member',iat:1,exp:2});
    await assert.rejects(()=>upload(body,expired));
    await transaction(db=>seedFixtures(db,{memberAlts:['Member Alt']}));
    const altData = await getPortalData(req('/account',null,member));
    assert.equal(altData.characters.length,2);
    assert.equal(altData.account.testAccount,true);
    assert.ok(altData.characters.every(c=>c.verified));
    await act({action:'set-main',characterId:'fixture-member-alt-1'},member);
    const mainChanged = await getPortalData(req('/account',null,member));
    assert.equal(mainChanged.characters.length,2);
    assert.equal(mainChanged.characters.filter(c=>c.isMain).length,1);
    assert.equal(mainChanged.characters.find(c=>c.isMain).name,'Member Alt');
    assert.equal(mainChanged.characters.find(c=>c.id === 'fixture-member-character').verified,true);
    process.env.BNET_CLIENT_ID = 'test-client'; process.env.BNET_CLIENT_SECRET = 'test-client-secret'; process.env.BNET_REDIRECT_URI = 'http://localhost:4321/auth/callback';
    const started = await beginBattleNet(req('/auth/start'));
    const state = new URL(started.headers.get('location')).searchParams.get('state');
    const oauthCookie = started.headers.get('set-cookie').split(';')[0];
    const callback = req(`/auth/callback?state=${state}&code=test-code`,null,oauthCookie);
    const fetchCalls = [];
    const fakeFetch = async (url) => {
      fetchCalls.push(url);
      return Response.json(url.endsWith('/token') ? {access_token:'test-access-token',token_type:'bearer'} : {sub:'123456',battletag:'Example#1234'});
    };
    const finished = await finishBattleNet(callback,fakeFetch);
    assert.deepEqual(fetchCalls,['https://oauth.battle.net/token','https://oauth.battle.net/userinfo']);
    const realCookie = finished.headers.getSetCookie().find(c=>c.startsWith('hh_session=')).split(';')[0];
    const realIdentity = await getPortalData(req('/account',null,realCookie));
    assert.equal(realIdentity.account.testAccount,false); assert.equal(realIdentity.account.role,null); assert.equal(realIdentity.guild,null);
    assert.deepEqual(realIdentity.characters,[]); assert.deepEqual(realIdentity.tokens,[]);
    await assert.rejects(()=>finishBattleNet(callback,fakeFetch));
    await assert.rejects(()=>act({action:'issue-token',scope:'guild'},realCookie));
    assert.equal((await getPool().query("SELECT count(*) FROM memberships WHERE account_id='bnet:123456'")).rows[0].count,'0');
  } finally {
    await getPool().end(); process.env.DATABASE_URL = oldUrl;
    await admin.query(`DROP SCHEMA ${schema} CASCADE`); await admin.end();
  }
});
